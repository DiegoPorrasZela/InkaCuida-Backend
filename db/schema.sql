CREATE TABLE IF NOT EXISTS usuario (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                  VARCHAR(120) NOT NULL,
    email                   VARCHAR(160) NOT NULL UNIQUE,
    password_hash           VARCHAR(255) NOT NULL,          -- BCrypt
    fecha_nacimiento        DATE,
    ciudad                  VARCHAR(80),
    consentimiento_aceptado BOOLEAN      NOT NULL,          -- Ley N.° 29733
    creado_en               TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

-- Carnet digital: la prescripción tal como la registró el paciente (HU01)
CREATE TABLE IF NOT EXISTS medicamento (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id           BIGINT       NOT NULL REFERENCES usuario(id),
    nombre               VARCHAR(120) NOT NULL,
    dosis                VARCHAR(60)  NOT NULL,
    frecuencia           VARCHAR(20)  NOT NULL
        CHECK (frecuencia IN ('UNA_VEZ_DIA','DOS_VECES_DIA','TRES_VECES_DIA','CADA_8_HORAS','CADA_12_HORAS')),
    fecha_inicio         DATE         NOT NULL,
    fecha_fin            DATE,
    indicaciones         VARCHAR(500),
    unidades_disponibles INTEGER,                           -- para la alerta de reposición (HU03)
    activo               BOOLEAN      NOT NULL,             -- borrado lógico
    CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE TABLE IF NOT EXISTS medicamento_horario (
    medicamento_id BIGINT     NOT NULL REFERENCES medicamento(id),
    orden          INTEGER    NOT NULL,
    hora           VARCHAR(5) NOT NULL,                     -- "HH:mm"
    PRIMARY KEY (medicamento_id, orden)
);

-- Cada dosis programada y la respuesta del paciente (HU02, HU05, HU06)
CREATE TABLE IF NOT EXISTS toma (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      BIGINT      NOT NULL REFERENCES usuario(id),
    medicamento_id  BIGINT      NOT NULL REFERENCES medicamento(id),
    fecha           DATE        NOT NULL,
    hora            VARCHAR(5)  NOT NULL,
    estado          VARCHAR(12) NOT NULL CHECK (estado IN ('PENDIENTE','TOMADA','OMITIDA')),
    respondida_en   TIMESTAMP(6) WITH TIME ZONE,
    pospuesta_hasta TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_toma_med_fecha_hora UNIQUE (medicamento_id, fecha, hora)
);
CREATE INDEX IF NOT EXISTS ix_toma_usuario_fecha ON toma (usuario_id, fecha);

-- Familiares autorizados por el paciente
CREATE TABLE IF NOT EXISTS cuidador (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT       NOT NULL REFERENCES usuario(id),
    nombre         VARCHAR(120) NOT NULL,
    email          VARCHAR(160) NOT NULL,
    parentesco     VARCHAR(60),
    recibe_alertas BOOLEAN      NOT NULL
);

